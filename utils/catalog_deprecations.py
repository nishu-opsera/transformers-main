"""Catalog active deprecations declared in the codebase (WO-023)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from transformers.utils.deprecation_utils import iter_registered_deprecations  # noqa: E402

DEFAULT_OUTPUT = REPO_ROOT / ".ci" / "active_deprecations.json"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="JSON report path (default: .ci/active_deprecations.json)",
    )
    args = parser.parse_args()

    records = iter_registered_deprecations()
    payload = {"count": len(records), "deprecations": records}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(records)} deprecation entries to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
